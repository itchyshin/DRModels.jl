# Parity of the Student and Gamma location-scale fits against drmTMB reference
# numbers. Refs #969 #937. Mismatches are @test_broken (tracked gaps, not
# silenced): they flip to "unexpectedly passed" -> an Error once the engine is
# fixed, forcing this file to be tightened.
#
# Reference numbers are GENERATED OUTPUTS only (no drmTMB source; MIT boundary).
#
# 1. Student, mean (1|Subject) + sigma ~ Days, lme4::sleepstudy (#937).
#    drmTMB 0.7.1 (0eb0467851cc2902556764bdca5441b7bc053be6), R 4.6.0:
#      drmTMB(drm_formula(Reaction ~ Days + (1 | Subject), sigma ~ Days),
#             family = student(), data = d)
#    logLik -887.7141 (df = 6); opt$par (mu, mu_Days, sigma, sigma_Days, nu eta,
#    log sd_Subject) = [253.2686, 9.6710, 2.7035, 0.0986, 0.9992, 3.481],
#    quoted from the #937 report. DRModels' default fit stops at the Gaussian
#    limit (nu eta ~ 27.9, logLik -891.9119), 4.4 below drmTMB's optimum.
#
# 2. Gamma sigma ~ x: NO drmTMB reference exists in the repo yet. The fixture
#    `positive-gamma-locscale` is generated by test/parity/gen_fixtures.R
#    (maintainer machine with R + drmTMB) and this testset runs only once it is
#    committed; until then it is an explicit @test_skip.
using DRModels
using Test

function _read_sleepstudy_parity()
    lines = readlines(joinpath(@__DIR__, "fixtures", "lme4", "sleepstudy.csv"))
    rows = [split(l, ',') for l in lines[2:end]]
    return (; Reaction = parse.(Float64, getindex.(rows, 1)),
              Days = parse.(Float64, getindex.(rows, 2)),
              Subject = String.(strip.(getindex.(rows, 3), '"')))
end

@testset "parity Student location-scale vs drmTMB (#937, #969)" begin
    dat = _read_sleepstudy_parity()
    f = bf(@formula(Reaction ~ 1 + Days + (1 | Subject)), @formula(sigma ~ 1 + Days))
    fit = drm(f, Student(); data = dat)

    ref_loglik = -887.7141
    ref_theta  = [253.2686, 9.6710, 2.7035, 0.0986, 0.9992, 3.481]

    @test length(fit.theta) == length(ref_theta)       # same parameterisation
    @test isfinite(loglik(fit))
    @test loglik(fit) <= ref_loglik + 1e-3             # never above drmTMB's optimum

    # Known mismatches (#937): stuck at nu -> Gaussian limit.
    @test_broken isapprox(loglik(fit), ref_loglik; atol = 0.05)
    @test_broken isapprox(fit.theta[5], ref_theta[5]; atol = 0.1)            # nu eta
    @test_broken isapprox(fit.theta[1:2], ref_theta[1:2]; atol = 0.5)        # mu
    @test_broken isapprox(fit.theta[3:4], ref_theta[3:4]; atol = 0.1)        # sigma
    # Decision of 25 Oct 2026 (#937): such a fit must not report converged.
    @test !is_converged(fit)
end

@testset "parity Gamma location-scale vs drmTMB (sigma ~ x)" begin
    dir = joinpath(@__DIR__, "parity", "fixtures", "positive-gamma-locscale")
    if isfile(joinpath(dir, "expected.toml"))
        include(joinpath(@__DIR__, "parity", "compare.jl"))
        include(joinpath(@__DIR__, "parity", "loadfixture.jl"))
        expected = load_expected(dir)
        data = load_data(dir)
        fit = drm(bf(@formula(y ~ x), @formula(sigma ~ x)), DRModels.Gamma(); data = data)
        @test compare_fit(fit, expected).passed
    else
        @info "positive-gamma-locscale fixture not committed; needs R + drmTMB (gen_fixtures.R)"
        @test_skip gamma_locscale_fixture_present
    end
end
