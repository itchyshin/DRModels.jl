# Gap-close wave 9 (refusal-gap map, groups 1/7/12 and 10).
#
# (A) A bare structured `kind(1 + x | g)` block with no `sd()` formula is, in native
#     drmTMB 0.8.1, the independent two-SD model (labelled `(1 + x | p | g)`: the
#     correlated one), i.e. the same model as `sd(g, kind, coef(·)) ~ 1` for both
#     coefficients. DRModels now completes the two intercept-only SD formulas for the
#     shapes whose explicit form is a supported route, and refuses everything else
#     exactly as before.
# (B) Gamma phylo(1 + x | g) and coordinate spatial(1 + x | g) with one SD formula per
#     coefficient (the Gamma two-field engine with the phylo/spatial q2 kernel).
#
# Oracles share no fitter code. Gaussian: exact dense MvNormal density of
# V = sum_k diag(w_k s_k) C diag(w_k s_k)' + sigma^2 I at the fitted parameters. Gamma
# and Poisson: an independent dense ForwardDiff Laplace in the standardised latent
# b ~ N(0, R ⊗ C) (R = I for the independent block, R = [1 rho; rho 1] for the labelled
# one). Tolerances fixed before the first run: |loglik - oracle| < 1e-6 (Gaussian),
# < 1e-5 (Laplace); the fit converged and every SE is finite.
# Fixtures: test/fixtures/q2_stable/psq2_{gaussian,poisson}_{phylo,spatial}.tsv (existing)
# and test/fixtures/gap_close/gamma_{phylo,spatial}.tsv (committed by `_gc_generate`).
using DRModels, Test, Random, LinearAlgebra
import Distributions, ForwardDiff
using SpecialFunctions: loggamma

const _GC_BITS = 5                          # 32 tips, balanced binary tree

function _gc_tree()
    G = 2^_GC_BITS
    ids = ["t$(lpad(i, 2, '0'))" for i in 1:G]
    nw(ix, root) = length(ix) == 1 ? "$(ids[ix[1]]):1.5" :
        "(" * nw(ix[1:end÷2], false) * "," * nw(ix[end÷2+1:end], false) * ")" * (root ? ";" : ":0.1")
    height = 1.5 + 0.1 * (_GC_BITS - 1)
    bits(i) = reverse(digits(i - 1; base = 2, pad = _GC_BITS))
    C = [i == j ? 1.0 : (findfirst(bits(i) .!= bits(j)) - 1) * 0.1 / height for i in 1:G, j in 1:G]
    return nw(collect(1:G), true), ids, C
end

function _gc_grid(G)
    side = round(Int, sqrt(G))
    xy = [(Float64(i), Float64(j)) for j in 0:side-1 for i in 0:side-1]
    D = [hypot(xy[k][1] - xy[l][1], xy[k][2] - xy[l][2]) for k in 1:G, l in 1:G]
    rng = Distributions.median([D[k, l] for k in 1:G for l in k+1:G])
    return xy, exp.(-D ./ rng) + 1e-6 * I
end

# Gamma fixture generator (kept for regeneration only; the committed TSVs are what is fitted).
function _gc_generate(C, ids, path; seed = 20261108, m = 10, cv = 0.5)
    rng = MersenneTwister(seed)
    G = length(ids)
    z0 = repeat([-1.0, 1.0], G ÷ 2)
    z1 = collect(range(-1.0, 1.0; length = G))[randperm(rng, G)]
    L = cholesky(Symmetric(C)).L
    u0 = exp.(log(0.45) .+ 0.3 .* z0) .* (L * randn(rng, G))
    u1 = exp.(log(0.3) .- 0.3 .* z1) .* (L * randn(rng, G))
    gi = repeat(1:G, inner = m)
    x = repeat(collect(range(-1.2, 1.2; length = m)), G)
    mu = exp.(0.5 .+ 0.3 .* x .+ u0[gi] .+ x .* u1[gi])
    k = 1 / cv^2
    y = [rand(rng, Distributions.Gamma(k, mu[i] / k)) for i in eachindex(mu)]
    ord = randperm(rng, length(y))
    open(path, "w") do io
        println(io, "# sumC=$(round(sum(C); digits = 3)) family=gamma generated by _gc_generate (seed $seed, cv $cv)")
        println(io, "y\tx\tz0\tz1\tid\tgi")
        for i in ord
            println(io, join((y[i], x[i], z0[gi[i]], z1[gi[i]], ids[gi[i]], gi[i]), '\t'))
        end
    end
end

# Reads psq2_<family>_<kind>.tsv (existing) or gap_close/gamma_<kind>.tsv (new).
function _gc_fixture(kind, ids, family)
    file = family === :gamma ? joinpath(@__DIR__, "fixtures", "gap_close", "gamma_$(kind).tsv") :
                               joinpath(@__DIR__, "fixtures", "q2_stable", "psq2_$(family)_$(kind).tsv")
    rows = [split(l, '\t') for l in readlines(file)[3:end]]
    col(j, T) = T === String ? String[r[j] for r in rows] : parse.(T, [r[j] for r in rows])
    data = (; y = col(1, Float64), x = col(2, Float64), z0 = col(3, Float64),
              z1 = col(4, Float64), id = col(5, String))
    gi = col(6, Int)
    z1g = zeros(length(ids)); z1g[gi] .= data.z1
    return (; data, gi, z0 = repeat([-1.0, 1.0], length(ids) ÷ 2), z1 = z1g)
end

_gc_level(kind) = kind === :phylo ? :phylogenetic : kind
_gc_mu(kind, label) = kind === :phylo ? (label ? @formula(y ~ x + phylo(1 + x | p | id)) : @formula(y ~ x + phylo(1 + x | id))) :
                      kind === :spatial ? @formula(y ~ x + spatial(1 + x | id)) :
                      kind === :relmat ? (label ? @formula(y ~ x + relmat(1 + x | p | id)) : @formula(y ~ x + relmat(1 + x | id))) :
                      @formula(y ~ x + animal(1 + x | id))
function _gc_sds(kind, z)
    lv = _gc_level(kind)
    f0 = z ? eval(Meta.parse("@formula(sd(id, $lv, coef(intercept)) ~ z0)")) : eval(Meta.parse("@formula(sd(id, $lv, coef(intercept)) ~ 1)"))
    f1 = z ? eval(Meta.parse("@formula(sd(id, $lv, coef(x)) ~ z1)")) : eval(Meta.parse("@formula(sd(id, $lv, coef(x)) ~ 1)"))
    return f0, f1
end
_gc_bf(fam, kind, label, sd) = begin
    parts = Any[_gc_mu(kind, label)]
    fam isa Poisson || push!(parts, @formula(sigma ~ 1))
    sd === :none || append!(parts, collect(_gc_sds(kind, sd === :z)))
    bf(parts...)
end

function _gc_blocks(fit)
    b = fit.blocks
    sdb = [last(p) for p in b if startswith(String(first(p)), "sdtarget_")]
    sig = [last(p) for p in b if first(p) === :sigma]
    beta = fit.theta[last(b[1])]
    logsig = isempty(sig) ? NaN : fit.theta[only(sig)][1]
    rho = [last(p) for p in b if first(p) === :recov]
    atanh_rho = isempty(rho) ? nothing : fit.theta[only(rho)][1]
    return beta, logsig, fit.theta[sdb[1]], fit.theta[sdb[2]], atanh_rho
end

function _gc_scales(fit, fx, z)
    _, _, a0, a1, _ = _gc_blocks(fit)
    z0 = z ? fx.z0 : ones(length(fx.z0)); z1 = z ? fx.z1 : ones(length(fx.z1))
    Z0 = z ? [ones(length(z0)) z0] : ones(length(z0), 1)
    Z1 = z ? [ones(length(z1)) z1] : ones(length(z1), 1)
    return exp.(Z0 * a0), exp.(Z1 * a1)
end

function _gc_gaussian_oracle(fit, fx, C, z)
    beta, logsig, _, _, _ = _gc_blocks(fit)
    d = fx.data; gi = fx.gi; n = length(d.y)
    s0, s1 = _gc_scales(fit, fx, z)
    V = [(s0[gi[i]] * s0[gi[j]] + d.x[i] * d.x[j] * s1[gi[i]] * s1[gi[j]]) * C[gi[i], gi[j]] for i in 1:n, j in 1:n]
    V += exp(2logsig) * I
    return Distributions.logpdf(Distributions.MvNormal(beta[1] .+ beta[2] .* d.x, Symmetric(V)), d.y)
end

function _gc_laplace_oracle(fit, fx, C, fam, z)
    beta, logsig, _, _, atanh_rho = _gc_blocks(fit)
    d = fx.data; gi = fx.gi; G = size(C, 1)
    s0, s1 = _gc_scales(fit, fx, z)
    rho = atanh_rho === nothing ? 0.0 : tanh(atanh_rho)
    R = [1.0 rho; rho 1.0]
    P = kron(inv(R), inv(Symmetric(C)))                 # prior precision of b = [b0; b1]
    ldP = -logdet(Symmetric(kron(R, C)))                # logdet P
    kshape = exp(-2logsig)
    function lik(eta)
        mu = exp.(eta)
        fam isa Poisson ? sum(d.y .* eta .- mu .- loggamma.(d.y .+ 1)) :
        fam isa NegBinomial2 ?
            sum(loggamma.(d.y .+ kshape) .- loggamma(kshape) .- loggamma.(d.y .+ 1) .+
                kshape .* log.(kshape ./ (kshape .+ mu)) .+ d.y .* log.(mu ./ (kshape .+ mu))) :
            sum(Distributions.logpdf.(Distributions.Gamma.(kshape, mu ./ kshape), d.y))
    end
    function joint(b)
        eta = beta[1] .+ beta[2] .* d.x .+ s0[gi] .* b[gi] .+ d.x .* s1[gi] .* b[G .+ gi]
        return lik(eta) - 0.5 * dot(b, P * b)
    end
    b = zeros(2G)
    for _ in 1:200
        g = ForwardDiff.gradient(joint, b); H = ForwardDiff.hessian(joint, b)
        step = -(Symmetric(H) \ g); b .+= step
        maximum(abs, step) < 1e-12 && break
    end
    H = -ForwardDiff.hessian(joint, b)
    # Laplace: joint(b*) + 0.5 logdet(P) - 0.5 logdet(H)  (the 2π constants cancel)
    return joint(b) + 0.5 * ldP - 0.5 * logdet(Symmetric(H))
end

@testset "gap close: bare structured q2 completes default SDs; Gamma phylo/spatial q2" begin
    nwk, ids, Cphy = _gc_tree()
    xy, Csp = _gc_grid(length(ids))
    coords = Dict(ids[k] => [xy[k]...] for k in eachindex(ids))
    Cof = Dict(:phylo => Cphy, :spatial => Csp)
    kw(kind) = kind === :phylo ? (; tree = nwk) : (; coords)

    @testset "(A) bare == explicit ~ 1, and equals the dense oracle" begin
        # (family, kind, label): the shapes drmTMB 0.8.1 fits without an sd() formula
        # and DRModels now completes.
        cases = [(Gaussian(), :spatial, false), (Poisson(), :spatial, false),
                 (Poisson(), :phylo, false), (NegBinomial2(), :spatial, false),
                 (Poisson(), :phylo, true)]
        for (fam, kind, label) in cases
            fsym = fam isa Gaussian ? :gaussian : fam isa Poisson ? :poisson : :nb2
            @testset "$fsym $kind label=$label" begin
                fx = _gc_fixture(kind, ids, fsym)
                C = Cof[kind]
                bare = drm(_gc_bf(fam, kind, label, :none), fam; data = fx.data, kw(kind)...)
                expl = drm(_gc_bf(fam, kind, label, :one), fam; data = fx.data, kw(kind)...)
                @test bare.converged
                @test all(isfinite, stderror(bare))
                @test loglikelihood(bare) == loglikelihood(expl)
                @test coef(bare) == coef(expl)
                @test length(DRModels._sd_target_parts(bare.formula)) == 2
                oracle = fam isa Gaussian ? _gc_gaussian_oracle(bare, fx, C, false) :
                         _gc_laplace_oracle(bare, fx, C, fam, false)
                @test loglikelihood(bare) ≈ oracle atol = (fam isa Gaussian ? 1e-6 : 1e-5)
            end
        end
        # relmat / animal: K and A in first-appearance row order (the kernel is the tip correlation).
        for fam in (Gaussian(), Poisson())
            fsym = fam isa Gaussian ? :gaussian : :poisson
            fxr = _gc_fixture(:phylo, ids, fsym)
            firstseen = unique(fxr.data.id)
            perm = [findfirst(==(s), ids) for s in firstseen]
            Kfs = Cphy[perm, perm]
            for kind in (:relmat, :animal)
                kwr = kind === :relmat ? (; K = Kfs) : (; A = Kfs, ids = firstseen)
                bare = drm(_gc_bf(fam, kind, false, :none), fam; data = fxr.data, kwr...)
                expl = drm(_gc_bf(fam, kind, false, :one), fam; data = fxr.data, kwr...)
                @test bare.converged
                @test loglikelihood(bare) == loglikelihood(expl)
                fxo = (; data = fxr.data, gi = [findfirst(==(s), firstseen) for s in fxr.data.id],
                         z0 = ones(length(ids)), z1 = ones(length(ids)))
                oracle = fam isa Gaussian ? _gc_gaussian_oracle(bare, fxo, Kfs, false) :
                         _gc_laplace_oracle(bare, fxo, Kfs, fam, false)
                @test loglikelihood(bare) ≈ oracle atol = (fam isa Gaussian ? 1e-6 : 1e-5)
            end
        end
    end

    @testset "(A) refusals stay exactly what they were" begin
        fx = _gc_fixture(:spatial, ids, :gaussian)
        gdat = fx.data
        # REML is completed for the Gaussian structured q2 cells (docs/dev-log/2026-11-09-gaussian-reml-routes2.md).
        @test drm(_gc_bf(Gaussian(), :spatial, false, :none), Gaussian(); data = gdat, coords,
                  method = :REML).estim_method === :REML
        # Labelled and bare is fitted for Poisson and, on phylo, NegBinomial2 (drmTMB 0.8.1 fits both; residual-refusals).
        nbfit = drm(_gc_bf(NegBinomial2(), :phylo, true, :none), NegBinomial2();
            data = _gc_fixture(:phylo, ids, :nb2).data, tree = nwk)
        @test isfinite(loglikelihood(nbfit))
        # An extra random term, or an sd() formula for something else, keeps the original route.
        extra = bf(@formula(y ~ x + spatial(1 + x | id) + (1 | z0)), @formula(sigma ~ 1))
        @test_throws ArgumentError drm(extra, Gaussian(); data = gdat, coords)
        # Missing provider: the existing route's message.
        @test_throws r"needs `coords" drm(_gc_bf(Gaussian(), :spatial, false, :none), Gaussian(); data = gdat)
        # A family without the explicit route is not touched (Gamma relmat/animal have it; Tweedie does not).
        @test_throws ArgumentError drm(_gc_bf(Gaussian(), :spatial, false, :none), Tweedie();
            data = merge(gdat, (; y = abs.(gdat.y))), coords)
    end

    @testset "(B) Gamma phylo/spatial (1 + x | g), SD formula per coefficient" begin
        for kind in (:phylo, :spatial), (z, label) in ((false, false), (true, false), (true, true), (false, true))
            kind === :spatial && label && continue          # drmTMB 0.8.1 refuses labelled spatial
            @testset "$kind z=$z labelled=$label" begin
                fx = _gc_fixture(kind, ids, :gamma)
                C = Cof[kind]
                fit = drm(_gc_bf(Gamma(), kind, label, z ? :z : :one), Gamma(); data = fx.data, kw(kind)...)
                @test fit.converged
                @test all(isfinite, stderror(fit))
                oracle = _gc_laplace_oracle(fit, fx, C, Gamma(), z)
                @test loglikelihood(fit) ≈ oracle atol = 1e-5
            end
        end
        # bare Gamma phylo/spatial is the same fit as the explicit `~ 1` pair
        for kind in (:phylo, :spatial)
            fx = _gc_fixture(kind, ids, :gamma)
            bare = drm(_gc_bf(Gamma(), kind, false, :none), Gamma(); data = fx.data, kw(kind)...)
            expl = drm(_gc_bf(Gamma(), kind, false, :one), Gamma(); data = fx.data, kw(kind)...)
            @test loglikelihood(bare) == loglikelihood(expl)
        end
        fx = _gc_fixture(:phylo, ids, :gamma)
        f = _gc_bf(Gamma(), :phylo, false, :one)
        fs = _gc_bf(Gamma(), :spatial, false, :one)
        @test_throws r"needs `tree" drm(f, Gamma(); data = fx.data)
        @test_throws r"was supplied" drm(f, Gamma(); data = fx.data, tree = nwk, coords)
        @test_throws r"needs `coords" drm(fs, Gamma(); data = _gc_fixture(:spatial, ids, :gamma).data)
        # labelled spatial: drmTMB 0.8.1 refuses it, and so does DRModels
        flab = bf(@formula(y ~ x + spatial(1 + x | p | id)), @formula(sigma ~ 1),
                  _gc_sds(:spatial, false)...)
        @test_throws ArgumentError drm(flab, Gamma(); data = _gc_fixture(:spatial, ids, :gamma).data, coords)
        # a non-ultrametric tree is refused (drmTMB's correlation scale)
        @test_throws r"ultrametric" drm(f, Gamma(); data = fx.data, tree = replace(nwk, "t01:1.5" => "t01:2.5"))
        # sigma must stay fixed
        fsig = bf(@formula(y ~ x + phylo(1 + x | id)), @formula(sigma ~ x),
                  _gc_sds(:phylo, false)...)
        @test_throws ArgumentError drm(fsig, Gamma(); data = fx.data, tree = nwk)
        # one SD formula is not enough
        one = bf(@formula(y ~ x + phylo(1 + x | id)), @formula(sd(id, phylogenetic, coef(x)) ~ z1))
        @test_throws ArgumentError drm(one, Gamma(); data = fx.data, tree = nwk)
        # marginal simulation of the fitted Gamma q2 (bootstrap path) runs and is positive
        fit = drm(f, Gamma(); data = fx.data, tree = nwk)
        sim = simulate(fit; data = fx.data, tree = nwk, rng = MersenneTwister(1))
        @test length(sim) == length(fx.data.y) && all(>(0), sim)
    end
end
