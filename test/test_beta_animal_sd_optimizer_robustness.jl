function _beta_opt_fixture(; G = 30, m = 12)
    labels = ["g$(j)" for j in 1:G]
    d = sqrt.(range(0.45, 2.6; length = G))
    R = [0.4^abs(i - j) for i in 1:G, j in 1:G]
    A = Matrix(Diagonal(d) * R * Diagonal(d))
    gidx = repeat(1:G; inner = m)
    x = repeat(collect(range(-1, 1; length = m)), G)
    z = repeat([-1.0, 1.0], G ÷ 2)[gidx]
    return (; y = copy(_BETA_OPT_Y), x, z, g = labels[gidx]), A
end

@testset "Beta animal SD fit is stable under 1e-12 data perturbations" begin
    data, A = _beta_opt_fixture()
    formula = bf(@formula(y ~ x + animal(1 | g)), @formula(sigma ~ 1),
                 @formula(sd(g, animal) ~ z))
    fit0 = drm(formula, DRModels.Beta(); data, A, se = false)
    @test fit0.converged
    rng = MersenneTwister(1)
    for k in 1:6
        y = data.y .* (1 .+ 1e-12 .* randn(rng, length(data.y)))
        fit = drm(formula, DRModels.Beta(); data = merge(data, (; y)), A, se = false)
        @test fit.converged
        # The perturbed problems are the same problem to about 1e-10, so the
        # optimum must agree; the early stop was 1 to 3.4 units short.
        @test fit.loglik ≈ fit0.loglik atol = 1e-3
    end
end

@testset "Beta animal SD stencil points never return the failed-fit sentinel" begin
    data, A = _beta_opt_fixture()
    gidx, G = DRModels._group_index(data.g)
    Xmu = hcat(ones(length(data.y)), data.x)
    Wsd = hcat(ones(G), [data.z[findfirst(==(gi), gidx)] for gi in 1:G])
    rng = MersenneTwister(1)
    y = data.y
    for _ in 1:2
        y = data.y .* (1 .+ 1e-12 .* randn(rng, length(data.y)))
    end
    theta = [0.0685550750971142, 0.27172898569546866, -1.010486170498662,
             -0.3041831964848928, 0.8756065997358764]
    # The central-difference stencil used by the optimizer: no point may hit the
    # 1e18 sentinel (before the fix, theta[4] +/- h did).
    for j in eachindex(theta), s in (-1, 1)
        h = 2e-4 * (1 + abs(theta[j]))
        t = copy(theta); t[j] += s * h
        @test DRModels._beta_animal_sd_laplace_nll(t, y, Xmu, Wsd, gidx, A) < 1e17
    end
end
