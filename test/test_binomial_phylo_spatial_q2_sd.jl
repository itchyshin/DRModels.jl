# Binomial (Bernoulli, logit) phylo and coordinate-spatial independent intercept-plus-slope q2:
#   y ~ x + phylo|spatial(1 + x | g),  sd(g, phylogenetic|spatial, coef(intercept)) ~ z0,
#   sd(g, phylogenetic|spatial, coef(x)) ~ z1,   two independent unit fields, rho fixed 0.
# Scope = native drmTMB 0.8.1: logit link and an unweighted 0/1 response only. R refuses
# probit/cloglog ("currently support only an intercept-only q1 term"), cbind() trials
# ("requires unweighted 0/1 Bernoulli responses") and, for spatial, the labelled form.
# Kernels: phylo = tip correlation of the tree (ape::vcv(tree, corr = TRUE)); spatial =
# exp(-d / median d) + 1e-6 I. The oracle shares no fitter code: kernels built by hand,
# logit likelihood written out, dense ForwardDiff Laplace in the standardised latent
# b ~ N(0, I2 (x) C), Newton to 1e-12. Tolerances fixed before the first run:
# |loglik - oracle| < 1e-5; fit converged; all SEs finite.
# Data are the committed TSVs under test/fixtures/binomial_phylo_spatial_q2 (MersenneTwister
# streams differ between Julia 1.10 and 1.12). They were generated by
# `_bpsq2_generate` below with StableRNG(20261108) (first and only seed tried).
using DRModels, Test, LinearAlgebra, StableRNGs
import Distributions, ForwardDiff
using Random: randperm, MersenneTwister
using Statistics: mean

const _BPSQ2_BITS = 5                       # 32 tips, balanced binary tree

function _bpsq2_tree()
    G = 2^_BPSQ2_BITS
    ids = ["t$(lpad(i, 2, '0'))" for i in 1:G]
    nw(ix, root) = length(ix) == 1 ? "$(ids[ix[1]]):1.5" :
        "(" * nw(ix[1:end÷2], false) * "," * nw(ix[end÷2+1:end], false) * ")" * (root ? ";" : ":0.1")
    height = 1.5 + 0.1 * (_BPSQ2_BITS - 1)
    bits(i) = reverse(digits(i - 1; base = 2, pad = _BPSQ2_BITS))
    C = [i == j ? 1.0 : (findfirst(bits(i) .!= bits(j)) - 1) * 0.1 / height for i in 1:G, j in 1:G]
    return nw(collect(1:G), true), ids, C
end

function _bpsq2_grid(G)
    side = round(Int, sqrt(G))
    xy = [(Float64(i), Float64(j)) for j in 0:side-1 for i in 0:side-1]
    D = [hypot(xy[k][1] - xy[l][1], xy[k][2] - xy[l][2]) for k in 1:G, l in 1:G]
    rng = Distributions.median([D[k, l] for k in 1:G for l in k+1:G])
    return xy, exp.(-D ./ rng) + 1e-6 * I
end

# Regeneration only (not run by the tests).
function _bpsq2_generate(C, ids; m = 24, seed = 20261108)
    rng = StableRNG(seed)
    G = length(ids)
    z0 = repeat([-1.0, 1.0], G ÷ 2)
    z1 = collect(range(-1.0, 1.0; length = G))[randperm(rng, G)]
    L = cholesky(Symmetric(C)).L
    u0 = exp.(log(0.9) .+ 0.3 .* z0) .* (L * randn(rng, G))
    u1 = exp.(log(0.8) .- 0.3 .* z1) .* (L * randn(rng, G))
    gi = repeat(1:G, inner = m)
    x = repeat(collect(range(-1.2, 1.2; length = m)), G)
    eta = 0.3 .+ 0.5 .* x .+ u0[gi] .+ x .* u1[gi]
    y = Float64.(rand(rng, length(eta)) .< 1 ./ (1 .+ exp.(-eta)))
    ord = randperm(rng, length(y))
    return (; y = y[ord], x = x[ord], z0 = z0[gi][ord], z1 = z1[gi][ord], id = ids[gi][ord],
            gi = gi[ord], z1g = z1)
end

function _bpsq2_write(path, fx, tag)
    open(path, "w") do io
        println(io, "# $tag generated by _bpsq2_generate (StableRNG(20261108), m = 24) on Julia $(VERSION)")
        println(io, "y\tx\tz0\tz1\tid\tgi")
        for i in eachindex(fx.y)
            println(io, join((fx.y[i], fx.x[i], fx.z0[i], fx.z1[i], fx.id[i], fx.gi[i]), '\t'))
        end
    end
end

function _bpsq2_fixture(kind, ids)
    lines = readlines(joinpath(@__DIR__, "fixtures", "binomial_phylo_spatial_q2", "binq2_$(kind).tsv"))
    rows = [split(l, '\t') for l in lines[3:end]]
    col(j, T) = T === String ? String[r[j] for r in rows] : parse.(T, [r[j] for r in rows])
    data = (; y = col(1, Float64), x = col(2, Float64), z0 = col(3, Float64),
              z1 = col(4, Float64), id = col(5, String))
    gi = col(6, Int)
    z1g = zeros(length(ids)); z1g[gi] .= data.z1
    return (; data, gi, z0 = repeat([-1.0, 1.0], length(ids) ÷ 2), z1 = z1g)
end

function _bpsq2_formula(kind)
    kind === :phylo ?
        bf(@formula(y ~ x + phylo(1 + x | id)),
           @formula(sd(id, phylogenetic, coef(intercept)) ~ z0),
           @formula(sd(id, phylogenetic, coef(x)) ~ z1)) :
        bf(@formula(y ~ x + spatial(1 + x | id)),
           @formula(sd(id, spatial, coef(intercept)) ~ z0),
           @formula(sd(id, spatial, coef(x)) ~ z1))
end

# Dense Laplace log-likelihood at theta = (beta0, beta1, a0 (2), a1 (2)).
function _bpsq2_oracle(theta, fx, C)
    d = fx.data; gi = fx.gi; G = size(C, 1)
    beta = theta[1:2]; a0 = theta[3:4]; a1 = theta[5:6]
    s0 = exp.(a0[1] .+ a0[2] .* fx.z0); s1 = exp.(a1[1] .+ a1[2] .* fx.z1)
    Ci = inv(Symmetric(C))
    function joint(b)
        eta = beta[1] .+ beta[2] .* d.x .+ s0[gi] .* b[gi] .+ d.x .* s1[gi] .* b[G .+ gi]
        lp = sum(d.y .* eta .- log1p.(exp.(eta)))
        return lp - 0.5 * (dot(b[1:G], Ci * b[1:G]) + dot(b[G+1:end], Ci * b[G+1:end]))
    end
    b = zeros(2G)
    for _ in 1:100
        g = ForwardDiff.gradient(joint, b); H = ForwardDiff.hessian(joint, b)
        step = -(Symmetric(H) \ g); b .+= step
        maximum(abs, step) < 1e-12 && break
    end
    H = -ForwardDiff.hessian(joint, b)
    return joint(b) - logdet(C) - 0.5 * logdet(Symmetric(H))
end

if get(ENV, "BPSQ2_REGENERATE", "") == "1"
    nwk0, ids0, Cp0 = _bpsq2_tree(); _, Cs0 = _bpsq2_grid(length(ids0))
    dir = joinpath(@__DIR__, "fixtures", "binomial_phylo_spatial_q2")
    _bpsq2_write(joinpath(dir, "binq2_phylo.tsv"), _bpsq2_generate(Cp0, ids0), "phylo")
    _bpsq2_write(joinpath(dir, "binq2_spatial.tsv"), _bpsq2_generate(Cs0, ids0), "spatial")
end

@testset "Binomial phylo/spatial (1 + x | g) q2 with coefficient SD formulas" begin
    nwk, ids, Cphy = _bpsq2_tree()
    xy, Csp = _bpsq2_grid(length(ids))
    coords = Dict(ids[k] => [xy[k]...] for k in eachindex(ids))
    for (kind, C) in ((:phylo, Cphy), (:spatial, Csp))
        @testset "$kind" begin
            fx = _bpsq2_fixture(kind, ids)
            data = fx.data
            kw = kind === :phylo ? (; tree = nwk) : (; coords)
            f = _bpsq2_formula(kind)
            fit = drm(f, Binomial(); data, kw...)
            @test fit.converged
            @test length(fit.theta) == 6
            @test all(isfinite, stderror(fit))
            # SEs are stable in the finite-difference step (the default 5e-4 step is
            # noise-amplified on this route; the fit uses 3e-3): within 3% of a 1e-2 step.
            H2 = DRModels._finite_hessian(fit.nll, fit.theta; h = 1e-2)
            @test maximum(abs.(stderror(fit) ./ sqrt.(diag(inv(Symmetric(H2)))) .- 1)) < 0.03
            @test !any(first(b) === :recov for b in fit.blocks)     # rho fixed at 0
            @test !haskey(fit.scales, :correlation)
            @test loglikelihood(fit) ≈ _bpsq2_oracle(fit.theta, fx, C) atol = 1e-5

            # Fitted SD scales and predict / predict_parameters.
            ordered = map((:intercept, :x)) do member
                item = only(filter(i -> i.target.member === member, DRModels._sd_target_parts(f)))
                DRModels._sd_target_block(item.target; disambiguate = true)
            end
            a0, a1 = coef(fit, ordered[1]), coef(fit, ordered[2])
            # group-level scales: tip order for phylo, first-seen level order for spatial
            lv = kind === :phylo ? collect(eachindex(ids)) : indexin(unique(data.id), ids)
            @test fit.scales[Symbol(string(ordered[1]), "_group")] ≈ exp.(a0[1] .+ a0[2] .* fx.z0[lv])
            @test fit.scales[Symbol(string(ordered[2]), "_group")] ≈ exp.(a1[1] .+ a1[2] .* fx.z1[lv])
            beta = coef(fit, :mu)
            nd = (; x = [-0.5, 0.0, 0.8], id = fill(first(data.id), 3), z0 = zeros(3), z1 = zeros(3))
            eta_nd = hcat(ones(3), nd.x) * beta
            @test predict(fit, nd; type = :link) ≈ eta_nd atol = 1e-10
            @test predict(fit, nd; type = :response) ≈ 1 ./ (1 .+ exp.(-eta_nd)) atol = 1e-10
            pp = predict_parameters(fit, data; se = false)
            @test pp[ordered[1]] ≈ fit.scales[ordered[1]]
            @test pp[ordered[2]] ≈ fit.scales[ordered[2]]

            # The marginal simulator draws the same two independent fields: its mean
            # response matches a hand-rolled Monte Carlo of the fitted model.
            Y = simulate(fit; nsim = 400, rng = MersenneTwister(11), data, kw...)
            @test size(Y) == (length(data.y), 400)
            @test all(v -> v == 0.0 || v == 1.0, Y)
            L = cholesky(Symmetric(C)).L
            s0 = exp.(a0[1] .+ a0[2] .* fx.z0); s1 = exp.(a1[1] .+ a1[2] .* fx.z1)
            mc = StableRNG(5); acc = zeros(length(data.y)); R = 1500
            for _ in 1:R
                b0 = s0 .* (L * randn(mc, length(ids))); b1 = s1 .* (L * randn(mc, length(ids)))
                eta = beta[1] .+ beta[2] .* data.x .+ b0[fx.gi] .+ data.x .* b1[fx.gi]
                acc .+= 1 ./ (1 .+ exp.(-eta))
            end
            @test abs(mean(Y) - mean(acc ./ R)) < 0.02          # Monte-Carlo noise ~ 0.005

            # Bridge: the R-shaped formula string reaches the same fit.
            lvl = kind === :phylo ? "phylogenetic" : "spatial"
            br = drm_bridge(; formula = "y ~ x + $kind(1 + x | id); " *
                "sd(id, $lvl, coef(intercept)) ~ z0; sd(id, $lvl, coef(x)) ~ z1",
                family = "binomial", data, kw..., newdata = nd)
            @test br["converged"]
            @test br["coefficients"] ≈ coef(fit) atol = 1e-6
            @test length(unique(br["coef_names"])) == length(br["coef_names"])
        end
    end

    @testset "refusals (R 0.8.1 scope) stay explicit" begin
        fx = _bpsq2_fixture(:phylo, ids)
        f = _bpsq2_formula(:phylo)
        fs = _bpsq2_formula(:spatial)
        fxs = _bpsq2_fixture(:spatial, ids)
        for link in (:probit, :cloglog)
            @test_throws r"logit link only" drm(f, Binomial(link = link); data = fx.data, tree = nwk, se = false)
            @test_throws r"logit link only" drm(fs, Binomial(link = link); data = fxs.data, coords, se = false)
        end
        cb = merge(fx.data, (; succ = fx.data.y, fail = 1.0 .- fx.data.y))
        fcb = bf(@formula(cbind(succ, fail) ~ x + phylo(1 + x | id)),
                 @formula(sd(id, phylogenetic, coef(intercept)) ~ z0),
                 @formula(sd(id, phylogenetic, coef(x)) ~ z1))
        @test_throws r"unweighted 0/1" drm(fcb, Binomial(); data = cb, tree = nwk, se = false)
        lab = bf(@formula(y ~ x + phylo(1 + x | p | id)),
                 @formula(sd(id, phylogenetic, coef(intercept)) ~ z0),
                 @formula(sd(id, phylogenetic, coef(x)) ~ z1))
        @test_throws r"labelled correlated form" drm(lab, Binomial(); data = fx.data, tree = nwk, se = false)
        one = bf(@formula(y ~ x + phylo(1 + x | id)), @formula(sd(id, phylogenetic, coef(x)) ~ z1))
        @test_throws r"one SD formula for the intercept" drm(one, Binomial(); data = fx.data, tree = nwk, se = false)
        bad = replace(nwk, "t01:1.5" => "t01:2.5")
        @test_throws r"ultrametric" drm(f, Binomial(); data = fx.data, tree = bad, se = false)
        @test_throws r"`K = …` was supplied" drm(f, Binomial(); data = fx.data, tree = nwk, K = Cphy, se = false)
        keep = fx.data.id .!= "t07"
        @test_throws r"every tip" drm(f, Binomial(); data = map(v -> v[keep], fx.data), tree = nwk, se = false)
        @test_throws r"requires a `coords|needs `coords" drm(fs, Binomial(); data = fxs.data, se = false)
        @test_throws ErrorException drm(f, Binomial(); data = merge(fx.data, (; y = 2.0 .* fx.data.y)),
                                       tree = nwk, se = false)
    end
end
