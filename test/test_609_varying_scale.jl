const DAT = (y = _Y, x = _X, g = _G)
const GRID_X = [-0.7, 0.0, 0.8]

# drmTMB origin/main 67703f541 (post-#1130), engine = "tmb", the super-tight
# Newton-polished reference from tests/testthat/test-optimizer-tolerance.R
# (`grad_tol = 1e-13`, max |gradient| 2.99e-14): newdata `mu` on the link scale
# (identity link) at GRID_X.
const R_REFERENCE_NEWDATA_MU = [0.16723687209213173, 0.54703874680876263, 0.98109803219919800]

_mu_newdata(fit) = (βμ = coef(fit, :mu); βμ[1] .+ βμ[2] .* GRID_X)

@testset "#609 item 2: the varying-scale ranef cell is at its optimum on the Julia side" begin
    @test length(DAT.y) == 144

    f0 = bf(@formula(y ~ x + (1 | g)), @formula(sigma ~ x))             # the programme cell
    f1 = bf(@formula(y ~ x + (1 | g)), @formula(sigma ~ x), @formula(sd(g) ~ 1))  # the LSS fitter
    fit0 = drm(f0, Gaussian(); data = DAT)
    fit1 = drm(f1, Gaussian(); data = DAT)
    @test fit0.converged && fit1.converged
    @test first.(fit0.blocks) == [:mu, :sigma, :resd]   # routes through _fit_ranef_gaussian
    @test first.(fit1.blocks) == [:mu, :sigma, :sd]     # routes through _fit_ranef_gaussian_lss

    # (1) Stationary point: the true gradient at the returned optimum, not just
    #     Optim's flag. Measured 4.2e-9 on both fitters at the default g_tol.
    @test norm(ForwardDiff.gradient(fit0.nll, fit0.theta), Inf) ≤ 1e-7
    @test norm(ForwardDiff.gradient(fit1.nll, fit1.theta), Inf) ≤ 1e-7

    # (2) Tightening g_tol by four orders does not move the optimum (measured
    #     5.2e-11 in θ; the 1.086e-5 cross-engine gap was not here).
    tight0 = drm(f0, Gaussian(); data = DAT, g_tol = 1e-12)
    tight1 = drm(f1, Gaussian(); data = DAT, g_tol = 1e-12)
    @test maximum(abs.(fit0.theta .- tight0.theta)) ≤ 1e-8
    @test maximum(abs.(fit1.theta .- tight1.theta)) ≤ 1e-8
    @test abs(fit0.loglik - tight0.loglik) ≤ 1e-10

    # (3) The two fitters are the same estimator on this cell (measured 1.6e-15).
    @test maximum(abs.(fit0.theta .- fit1.theta)) ≤ 1e-9

    # (4) Cross-engine closure: drmTMB's post-#1130 reference, at 100x inside
    #     the programme's 4e-6 parity bar (measured 1.3e-11 at x = 0.8).
    @test maximum(abs.(_mu_newdata(fit0) .- R_REFERENCE_NEWDATA_MU)) < 4e-8
    @test maximum(abs.(_mu_newdata(tight0) .- R_REFERENCE_NEWDATA_MU)) < 4e-8
end

